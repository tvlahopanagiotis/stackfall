#!/usr/bin/env python3
"""Build the installable Stackfall app from the artifact page.

Usage: python3 build.py /path/to/stackfall.html
Writes index.html and sw.js next to this script. The artifact page has no
doctype/head/body (the artifact host adds them), so this adds a real document
shell, swaps Google Fonts for the bundled copies, and registers the service
worker that makes the game work offline.
"""
import hashlib, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else here.parent / 'stackfall.html').read_text()

# Split the artifact into head material (title, meta, links, style) and body.
cut = src.index('</style>') + len('</style>')
head, body = src[:cut], src[cut:]
head = re.sub(r'<link rel="preconnect"[^>]*>\s*', '', head)
head = re.sub(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^>]*>',
              '<link rel="stylesheet" href="fonts.css">', head)
head = head.replace('<meta name="claude:viewport-fit-sides" content="cover">\n', '')
assert 'googleapis' not in head + body, 'unexpected remote font reference'

shell_head = '''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no">
<meta name="theme-color" content="#1E3B35">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Stackfall">
<meta name="description" content="A falling-block puzzle game with a roguelite Run mode.">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="favicon-32.png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<style>[hidden]{display:none!important}html{background:#1E3B35}body{margin:0;overscroll-behavior:none;-webkit-tap-highlight-color:transparent}</style>
'''
register = '''
<script>
if ('serviceWorker' in navigator && location.protocol !== 'file:') {
  addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));
}
</script>
'''
page = shell_head + head + '\n</head>\n<body>\n' + body.strip() + '\n' + register + '</body>\n</html>\n'
(here / 'index.html').write_text(page)

# Service worker: precache everything; the cache name changes whenever any file
# changes, so a new build replaces the old one on the next online launch.
files = ['./', 'index.html', 'fonts.css', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png',
         'apple-touch-icon.png', 'favicon-32.png'] + sorted('fonts/' + p.name for p in (here / 'fonts').glob('*.woff2'))
h = hashlib.sha256()
for f in files[1:]:
    h.update((here / f).read_bytes())
version = h.hexdigest()[:12]
sw = f'''// Generated by build.py
const CACHE = 'stackfall-{version}';
const FILES = {files!r};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  // Page: try the network first so updates arrive, fall back to the cached copy offline.
  if (e.request.mode === 'navigate') {{
    e.respondWith(fetch(e.request).then(r => {{
      const copy = r.clone(); caches.open(CACHE).then(c => c.put('index.html', copy)); return r;
    }}).catch(() => caches.match('index.html')));
    return;
  }}
  e.respondWith(caches.match(e.request).then(hit => hit || fetch(e.request)));
}});
'''
(here / 'sw.js').write_text(sw)
print(f'index.html {len(page):,} bytes, cache {version}, {len(files)} files')
